def _deal(
    deal_id: str,
    account_id: str,
    name: str,
    amount: float,
    probability: float,
    stage: DealStage,
    forecast: ForecastCategory,
    service: ServiceLine,
    source: DealSource,
    owner: str,
    created: date,
    close: date,
    last_activity: date,
    days_in_stage: int,
    qualification: Qualification,
    proposal_sent: date = None,
    next_meeting: date = None,
    founder_involved: bool = False,
    objection: str = None,
) -> Deal:
    return Deal(
        deal_id=deal_id,
        account_id=account_id,
        deal_name=name,
        stage=stage,
        forecast_category=forecast,
        service_line=service,
        source=source,
        amount_usd=amount,
        probability=probability,
        owner=owner,
        created_date=created,
        expected_close_date=close,
        last_meaningful_activity_date=last_activity,
        proposal_sent_date=proposal_sent,
        next_meeting_date=next_meeting,
        days_in_stage=days_in_stage,
        founder_involved=founder_involved,
        qualification=qualification,
        primary_objection=objection,
    )


